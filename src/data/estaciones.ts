/**
 * Directorio de Estaciones de Bomberos en México
 * Fuente: datos públicos de cuerpos de bomberos municipales, estatales e industriales.
 * Última actualización: 2026-06
 */

export type TipoEstacion =
  | 'Municipal'
  | 'Estatal'
  | 'Industrial'
  | 'Aeropuerto'
  | 'PEMEX'
  | 'CFE'
  | 'Voluntarios';

/** Nivel de verificación editorial del registro */
export type Confianza = 'alta' | 'media' | 'baja';

export interface Coordenadas {
  lat: number;
  lng: number;
}

export interface RedesEstacion {
  facebook?: string;
  instagram?: string;
  x?: string;
}

export interface EstacionBomberos {
  id: string;
  nombre: string;
  slug: string;
  estado: string;
  ciudad: string;
  municipio: string;
  tipo: TipoEstacion;
  direccion?: string;
  telefono?: string;
  telefonoEmergencias?: string;
  servicios: string[];
  certificaciones?: string[];
  descripcion?: string;
  fundacion?: number;
  activa: boolean;
  /* ── Campos pro (modelo v2) ── */
  coordenadas?: Coordenadas;
  sitioWeb?: string;
  redes?: RedesEstacion;
  fuentes?: string[];        // URLs de fuentes oficiales que respaldan el registro
  verificadoEl?: string;     // ISO 'YYYY-MM' de la última verificación
  confianza?: Confianza;     // nivel de verificación (alta/media/baja)
  telefonosAdicionales?: string[]; // otras líneas de contacto verificadas
  email?: string;            // correo de contacto oficial
  operador?: string;         // organismo que opera la unidad (ARFF, puerto, PEMEX, CFE)
}

export interface EstadoDirectorio {
  nombre: string;
  slug: string;
  abreviatura: string;
  region: string;
  estaciones: EstacionBomberos[];
}

