/** Estación por estado-slug + estación-slug (para rutas L3) */
export function estacionPorSlug(estadoSlug: string, estacionSlug: string): { estado: EstadoDirectorio; estacion: EstacionBomberos } | undefined {
  const estado = estados.find((e) => e.slug === estadoSlug);
  if (!estado) return undefined;
  const estacion = estado.estaciones.find((s) => s.slug === estacionSlug);
  if (!estacion) return undefined;
  return { estado, estacion };
}

