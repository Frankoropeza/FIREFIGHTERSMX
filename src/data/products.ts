export interface Product {
  slug: string;
  title: string;
  description: string;
  category: string;
  /** Grupo de catálogo: marca o, en líneas genéricas (PQS ABC, CO2, Red Hidráulica…), la línea. */
  brand?: string;
  /** Fabricante real del modelo cuando `brand` es una línea genérica. Es el único
   *  valor que habilita el claim «distribuidor autorizado de …». */
  fabricante?: string;
  norm?: string;
  /** Número de parte o referencia del fabricante (schema `mpn`). */
  mpn?: string;
  /** Precio de referencia publicado en MXN. Sólo con él se emite Product + Offer
   *  (Google invalida un Product sin precio, reseñas ni calificación). */
  precio?: { valor: number; iva: 'incluido' | 'mas-iva'; vigenteHasta: string };
  badge?: string;
  image?: string;
  /** Fotografías adicionales DEL MISMO MODELO (nunca de otros modelos). */
  galeria?: string[];
  href: string;
  /** Tier de mercado, e.g. "Internacional" */
  tier?: string;
  /** Especificaciones técnicas clave para mostrar como chips */
  specs?: {
    /* Trajes */
    tpp?: string;
    thl?: string;
    outer?: string;
    weight?: string;
    extra?: string;
    colores?: string;
    cert_lab?: string;
    barrera_humedad?: string;
    forro_termico?: string;
    configuracion?: string;
    /* Cascos */
    norma?: string;
    material?: string;
    protector?: string;
    suspension?: string;
    peso?: string;
    /* SCBA */
    autonomia?: string;
    cilindro?: string;
    electronica?: string;
    /* Cámaras térmicas */
    resolucion?: string;
    sensor?: string;
    /* Herramientas de rescate */
    fuerza?: string;
    rango?: string;
    fuente?: string;
    /* Sistemas CI */
    tipo_sis?: string;
    cobertura?: string;
    listado?: string;
    ideal?: string;
    /* HAZMAT */
    nivel_haz?: string;
    barrera?: string;
    gases?: string;
    /* Drones */
    alcance?: string;
    ip?: string;
    /* Señalización y emergencia */
    bateria?: string;
    potencia?: string;
    prueba?: string;
    capacidad?: string;
  };
  /** Frase de certificación del hero de la ficha. Úsese cuando el modelo NO tenga
   *  certificación de laboratorio acreditado (marcas que declaran "equivalencia"). */
  normClaim?: string;
  /** Frase de dossier documental del hero de la ficha (override del texto por defecto). */
  dossierClaim?: string;
  /** Copy factual para fichas que no deben usar los claims institucionales por defecto. */
  detailIntro?: string[];
  suppressDefaultClaims?: boolean;
  /** Guía de selección propia del modelo (párrafos). Hechos del fabricante y
   *  explicación de norma o aplicación; nada inventado sobre el producto. */
  seleccion?: string[];
  /** Casos de uso propios del modelo (sustituyen a los genéricos de la categoría). */
  idealPara?: string[];
  aConsiderar?: string[];
  /** Presentaciones, componentes o accesorios que publica el fabricante. */
  incluye?: string[];
  /** Preguntas frecuentes específicas del modelo (FAQPage). */
  faqs?: { q: string; a: string }[];
  /** Fuentes del fabricante que respaldan la ficha (hoja técnica, página oficial). */
  fuentes?: { titulo: string; url: string }[];
  /** Tres características destacadas */
  features?: string[];
  /** Si es el modelo estelar de la categoría */
  highlight?: boolean;
}

/** Valores de `brand` que nombran una línea de catálogo, no un fabricante. */
