/** Fabricante declarable de un producto; `undefined` si no hay fabricante confirmado. */
export const fabricanteDe = (p: Product): string | undefined =>
  p.fabricante ?? (p.brand && !LINEAS_GENERICAS.has(p.brand) ? p.brand : undefined);

