export interface Product {
  slug: string;
  title: string;
  description: string;
  category: string;
  brand?: string;
  norm?: string;
  badge?: string;
  image?: string;
  href: string;
  /** Tier de mercado, e.g. "Tier 1 · Internacional" */
  tier?: string;
  /** Especificaciones técnicas clave para mostrar como chips */
  specs?: {
    /* Trajes */
    tpp?: string;
    thl?: string;
    outer?: string;
    weight?: string;
    extra?: string;
    colores?: string;
    cert_lab?: string;
    /* Cascos */
    norma?: string;
    material?: string;
    protector?: string;
    suspension?: string;
    peso?: string;
    /* SCBA */
    autonomia?: string;
    cilindro?: string;
    electronica?: string;
    /* Cámaras térmicas */
    resolucion?: string;
    sensor?: string;
    /* Herramientas de rescate */
    fuerza?: string;
    rango?: string;
    fuente?: string;
    /* Sistemas CI */
    tipo_sis?: string;
    cobertura?: string;
    listado?: string;
    ideal?: string;
    /* HAZMAT */
    nivel_haz?: string;
    barrera?: string;
    gases?: string;
    /* Drones */
    alcance?: string;
    ip?: string;
    /* Señalización y emergencia */
    bateria?: string;
    potencia?: string;
    prueba?: string;
    capacidad?: string;
  };
  /** Frase de certificación del hero de la ficha. Úsese cuando el modelo NO tenga
   *  certificación de laboratorio acreditado (marcas que declaran "equivalencia"). */
  normClaim?: string;
  /** Frase de dossier documental del hero de la ficha (override del texto por defecto). */
  dossierClaim?: string;
  /** Copy factual para fichas que no deben usar los claims institucionales por defecto. */
  detailIntro?: string[];
  suppressDefaultClaims?: boolean;
  /** Tres características destacadas */
  features?: string[];
  /** Si es el modelo estelar de la categoría */
  highlight?: boolean;
}

